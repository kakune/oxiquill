import { outputArtifactLimits } from '../../lib/doc-runtime/output-limits.mjs';

export function generateHaskellOutput() {
  return String.raw`-- @generated by oxiquill docgen. Do not edit by hand.
-- SPDX-License-Identifier: MIT OR Apache-2.0
module Oxiquill.Output
  ( JsonValue(..), NumberFormat(..), defaultNumberFormat, TableColumn(..), tableColumn,
    Outcome(..), outcome, OutcomeDiagnostic(..), displayOutcome,
    displayJson, displayTable, displayTableWith, displayChart, putText ) where

import Data.Char (ord)
import Data.List (intercalate)
import Numeric (showHex)
import System.IO (hFlush, stdout)

data JsonValue
  = JsonNull
  | JsonBool Bool
  | JsonInteger Integer
  | JsonNumber Double
  | JsonString String
  | JsonArray [JsonValue]
  | JsonObject [(String, JsonValue)]
  deriving (Eq)

displayJson :: JsonValue -> IO ()
displayJson value = emit (JsonObject [("kind", JsonString "json"), ("value", value)])

displayChart :: JsonValue -> IO ()
displayChart spec = emit (JsonObject [("kind", JsonString "chart"), ("spec", spec)])

data NumberFormat = NumberFormat
  { significantDigits :: Maybe Int
  , fractionDigits :: Maybe Int
  , notation :: Maybe String
  , unit :: Maybe String
  } deriving (Eq)

defaultNumberFormat :: NumberFormat
defaultNumberFormat = NumberFormat Nothing Nothing Nothing Nothing

data TableColumn = TableColumn
  { columnKey :: String
  , columnLabel :: String
  , columnType :: Maybe String
  , columnFormat :: Maybe NumberFormat
  , columnNullText :: Maybe String
  } deriving (Eq)

tableColumn :: String -> String -> TableColumn
tableColumn key label = TableColumn key label Nothing Nothing Nothing

data OutcomeDiagnostic = OutcomeDiagnostic
  { diagnosticName :: String
  , diagnosticValue :: Double
  , diagnosticUnit :: Maybe String
  } deriving (Eq)

data Outcome = Outcome
  { outcomeState :: String
  , outcomeLabel :: String
  , outcomeExplanation :: Maybe String
  , outcomeStatus :: Maybe String
  , outcomeDiagnostics :: [OutcomeDiagnostic]
  } deriving (Eq)

outcome :: String -> String -> Outcome
outcome state label = Outcome state label Nothing Nothing []

optional :: String -> (a -> JsonValue) -> Maybe a -> [(String, JsonValue)]
optional key encode = maybe [] (\value -> [(key, encode value)])

formatJson :: NumberFormat -> JsonValue
formatJson value = JsonObject
  (optional "significantDigits" (JsonInteger . toInteger) (significantDigits value)
  ++ optional "fractionDigits" (JsonInteger . toInteger) (fractionDigits value)
  ++ optional "notation" JsonString (notation value)
  ++ optional "unit" JsonString (unit value))

columnJson :: TableColumn -> JsonValue
columnJson value = JsonObject
  ([("key", JsonString (columnKey value)), ("label", JsonString (columnLabel value))]
  ++ optional "type" JsonString (columnType value)
  ++ optional "format" formatJson (columnFormat value)
  ++ optional "nullText" JsonString (columnNullText value))

displayOutcome :: Outcome -> IO ()
displayOutcome value = emit (JsonObject
  ([("kind", JsonString "outcome"), ("state", JsonString (outcomeState value)), ("label", JsonString (outcomeLabel value))]
  ++ optional "explanation" JsonString (outcomeExplanation value)
  ++ optional "status" JsonString (outcomeStatus value)
  ++ if null (outcomeDiagnostics value) then []
     else [("diagnostics", JsonArray (map diagnostic (outcomeDiagnostics value)))]))
  where
    diagnostic entry = JsonObject
      ([("name", JsonString (diagnosticName entry)), ("value", finite (diagnosticValue entry))]
      ++ optional "unit" JsonString (diagnosticUnit entry))
    finite number = if isNaN number || isInfinite number then JsonNull else JsonNumber number

displayTable :: [String] -> [[JsonValue]] -> IO ()
displayTable labels = displayTableWith (zipWith (tableColumn . show) [0 :: Int ..] labels)

displayTableWith :: [TableColumn] -> [[JsonValue]] -> IO ()
displayTableWith descriptors rows = do
  let columnPreview = take (${outputArtifactLimits.columnsPerTable} + 1) descriptors
      columns = take ${outputArtifactLimits.columnsPerTable} columnPreview
      rowPreview = take (${outputArtifactLimits.rowsPerTable} + 1) rows
      retained = take ${outputArtifactLimits.rowsPerTable} rowPreview
      truncated = length columnPreview > ${outputArtifactLimits.columnsPerTable}
        || length rowPreview > ${outputArtifactLimits.rowsPerTable}
        || any ((> length columns) . length . take (length columns + 1)) retained
      values row = JsonArray (take (length columns) (row ++ repeat JsonNull))
      total = if length rowPreview <= ${outputArtifactLimits.rowsPerTable}
        then [("rowCount", JsonInteger (toInteger (length rowPreview)))] else []
  emit (JsonObject
    ([("kind", JsonString "table")
     ,("columns", JsonArray (map columnJson columns))
     ,("rows", JsonArray (map values retained))
     ,("truncated", JsonBool truncated)] ++ total))

-- Double the reserved record separator in ordinary text.
putText :: String -> IO ()
putText = putStr . concatMap escapeMarker
  where
    escapeMarker '\x1e' = "\x1e\x1e"
    escapeMarker character = [character]

emit :: JsonValue -> IO ()
emit value = do
  -- Escaping non-ASCII characters makes character length equal UTF-8 byte length.
  let encoded = take (${outputArtifactLimits.workerResponseBytes} + 1) (encodeJson value)
      size = length encoded
  if size > ${outputArtifactLimits.workerResponseBytes}
    then fail "Haskell output exceeded the frame byte limit."
    else do
      putStr ("\x1eOXIQUILL/1 " ++ show size ++ "\n" ++ encoded ++ "\x1f")
      hFlush stdout

encodeJson :: JsonValue -> String
encodeJson JsonNull = "null"
encodeJson (JsonBool value) = if value then "true" else "false"
encodeJson (JsonInteger value) = show value
encodeJson (JsonNumber value)
  | isNaN value || isInfinite value = error "JSON numbers must be finite."
  | otherwise = show value
encodeJson (JsonString value) = quote value
encodeJson (JsonArray values) = "[" ++ intercalate "," (map encodeJson values) ++ "]"
encodeJson (JsonObject fields) = "{" ++ intercalate ","
  [quote key ++ ":" ++ encodeJson value | (key, value) <- fields] ++ "}"

quote :: String -> String
quote value = "\"" ++ concatMap escape value ++ "\""
  where
    escape '"' = "\\\""
    escape '\\' = "\\\\"
    escape character
      | code >= 0xd800 && code <= 0xdfff = error "JSON strings must contain Unicode scalar values."
      | code >= 0x10000 = unicode (0xd800 + div (code - 0x10000) 0x400)
          ++ unicode (0xdc00 + mod (code - 0x10000) 0x400)
      | code < 0x20 || code > 0x7e = unicode code
      | otherwise = [character]
      where code = ord character
    unicode code = let digits = showHex code "" in "\\u" ++ replicate (4 - length digits) '0' ++ digits
`;
}
